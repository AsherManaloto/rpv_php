<?php
require __DIR__ . '/includes/bootstrap.php';
login_required();

$reports = [
    'customers'       => ['Customer Report', 'SELECT account_id,company_name,contact_person,email,phone,status FROM customers'],
    'inventory'       => ['Inventory Report', 'SELECT item_code,item_name,category,quantity,reserved_quantity,reorder_level,location FROM inventory_items'],
    'suppliers'       => ['Supplier Report', 'SELECT supplier_code,name,category,contact_person,email,phone,status FROM suppliers'],
    'projects'        => ['Project Report', 'SELECT project_code,project_name,department,manager,start_date,end_date,budget,status,progress FROM projects'],
    'purchase_orders' => ['Purchase Order Report', 'SELECT po_number,order_date,expected_delivery,total_value,status FROM purchase_orders'],
    'quotations'      => ['Quotation Report', 'SELECT quotation_no,description,total_amount,valid_until,status,created_at FROM quotations'],
];

// ---------------- CSV download ----------------
if (isset($_GET['generate'])) {
    $key = (string) $_GET['generate'];
    if (!isset($reports[$key])) {
        http_response_code(404);
        exit('Report not found.');
    }
    [$title, $sql] = $reports[$key];
    $rows = query_all($sql);
    execute('INSERT INTO generated_reports(report_name,report_type,generated_by) VALUES (?,?,?)', [$title, $key, $_SESSION['user_id']]);

    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="' . $key . '_report.csv"');
    $out = fopen('php://output', 'w');
    fwrite($out, "\xEF\xBB\xBF"); // UTF-8 BOM so Excel opens it correctly
    if ($rows) {
        fputcsv($out, array_keys($rows[0]), ',', '"', '\\');
        foreach ($rows as $r) {
            fputcsv($out, $r, ',', '"', '\\');
        }
    } else {
        fputcsv($out, ['No data'], ',', '"', '\\');
    }
    fclose($out);
    exit;
}

$cards = [
    ['Customers', 'Customer account summary', 'customers'],
    ['Inventory', 'Stock levels and low-stock items', 'inventory'],
    ['Suppliers', 'Supplier directory and status', 'suppliers'],
    ['Projects', 'Project progress and status', 'projects'],
    ['Purchase Orders', 'PO amounts and delivery status', 'purchase_orders'],
    ['Quotations', 'Quotation values and approval status', 'quotations'],
];
$recent = query_all('SELECT r.*, u.full_name FROM generated_reports r LEFT JOIN users u ON u.id=r.generated_by ORDER BY r.created_at DESC LIMIT 15');

layout_start('Reports - RPV', 'reports');
?>
<div class="page-head"><div><h1>Reports</h1><p>View and download system reports.</p></div></div>

<div class="report-grid">
    <?php foreach ($cards as [$title, $desc, $key]): ?>
        <div class="report-card">
            <div class="report-icon">▤</div>
            <h3><?= h($title) ?></h3>
            <p><?= h($desc) ?></p>
            <a class="btn primary" href="reports.php?generate=<?= h($key) ?>">Generate CSV</a>
        </div>
    <?php endforeach; ?>
</div>

<h2>Recent Reports</h2>
<div class="table-wrap">
    <table>
        <thead><tr><th>Report</th><th>Type</th><th>Generated By</th><th>Date</th></tr></thead>
        <tbody>
        <?php foreach ($recent as $r): ?>
            <tr><td><?= h($r['report_name']) ?></td><td><?= h($r['report_type']) ?></td><td><?= dash($r['full_name']) ?></td><td><?= h($r['created_at']) ?></td></tr>
        <?php endforeach; ?>
        <?php if (!$recent): ?><tr><td colspan="4">No generated reports yet.</td></tr><?php endif; ?>
        </tbody>
    </table>
</div>
<?php
layout_end();
page_end();
